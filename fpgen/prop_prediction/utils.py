# Словарь для кодирования аминокислотных последовательностей
VOCAB = {char: (i + 1) for i, char in enumerate('ACDEFGHIKLMNPRQSTVWYX')}
PAD_TOKEN = '?'  # Символ для заполнения последовательностей
VOCAB[PAD_TOKEN] = 0  # Нулевой индекс зарезервирован для символа заполнения

# Обратный словарь для декодирования (индекс -> символ)
VOCAB_REV = {v: k for k, v in VOCAB.items()}

def encode(sequence: str) -> list[int]:
    
    '''
    Кодирует аминокислотную последовательность в список индексов.
    
    Параметры:
        sequence (str): Строка с аминокислотной последовательностью 
                        (однобуквенные обозначения)
    
    Возвращает:
        list[int]: Список индексов, соответствующих символам последовательности.
                   Символ заполнения '?' имеет индекс 0.
    
    Пример:
        >>> encode('ACD')
        [1, 2, 3]
        >>> encode('ACZ')  # Z неизвестен, заменяется на X
        [1, 2, 20]
    '''

    return [VOCAB.get(s, VOCAB['X']) for s in sequence]